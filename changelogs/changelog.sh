#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
OUTPUT="$REPO_ROOT/CHANGELOG.md"

CHECK_ONLY=0
if [[ "${1:-}" == "--check" ]]; then
  CHECK_ONLY=1
elif [[ -n "${1:-}" ]]; then
  echo "Usage: $0 [--check]" >&2
  exit 2
fi

mapfile -t VERSION_FILES < <(
  find "$SCRIPT_DIR" -maxdepth 1 -type f -name 'v*.md' -printf '%f\n' | sort -rV
)

if [[ ${#VERSION_FILES[@]} -eq 0 ]]; then
  echo "No version changelog files found in $SCRIPT_DIR (expected v*.md)." >&2
  exit 1
fi

TMP_FILE="$(mktemp)"
trap 'rm -f "$TMP_FILE"' EXIT

{
  printf '# Changelog\n\n'
  printf '<!-- Generated by changelogs/changelog.sh. Edit files in changelogs/ instead. -->\n'

  if [[ -f "$SCRIPT_DIR/unreleased.md" ]]; then
    printf '\n'
    cat "$SCRIPT_DIR/unreleased.md"
  fi

  for fname in "${VERSION_FILES[@]}"; do
    printf '\n'
    # Strip trailing blank lines so sections have consistent spacing
    awk '
      { lines[NR] = $0 }
      NF { last = NR }
      END {
        for (i = 1; i <= last; i++) print lines[i]
      }
    ' "$SCRIPT_DIR/$fname"
  done
} > "$TMP_FILE"

if [[ "$CHECK_ONLY" -eq 1 ]]; then
  if [[ ! -f "$OUTPUT" ]] || ! cmp -s "$TMP_FILE" "$OUTPUT"; then
    echo "CHANGELOG.md is out of date. Run ./changelogs/changelog.sh to regenerate it." >&2
    exit 1
  fi
  echo "CHANGELOG.md is up to date."
  exit 0
fi

mv "$TMP_FILE" "$OUTPUT"
echo "Generated $OUTPUT from ${#VERSION_FILES[@]} version file(s)."
